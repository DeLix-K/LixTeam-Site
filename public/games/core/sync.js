// What the leaderboard counts, and how a browser's career is turned into a submission. Pure functions only: no network,
// no storage. The server (supabase/rootline/001_accounts.sql) recomputes every XP figure itself from the mission table
// that missionsSql() writes, so this file only has to agree with it, and the tests check that it does.

import { MISSIONS } from './missions.js';
import { xpReward, pathOfMission } from './career.js';

// One row per career mission: what a bronze, silver and gold is worth on the board.
// Mission XP only. The one-off "tried it" bonus and practice XP are not on the board.
export function missionRows() {
  return MISSIONS.map((m) => ({
    id: m.id,
    path: pathOfMission(m),
    is_exam: !!m.exam,
    minutes: Math.max(1, Math.round(m.minutes || 0)),
    xp1: xpReward(m, 1),
    xp2: xpReward(m, 2),
    xp3: xpReward(m, 3),
  }));
}

const lit = (v) => (typeof v === 'string' ? `'${v.replace(/'/g, "''")}'` : typeof v === 'boolean' ? (v ? 'true' : 'false') : String(v));

// The text of supabase/rootline/002_missions.sql.
export function missionsSql(rows) {
  const lines = rows.map((r) => `  (${lit(r.id)}, ${lit(r.path)}, ${lit(r.is_exam)}, ${r.minutes}, ${r.xp1}, ${r.xp2}, ${r.xp3})`);
  return [
    '-- Generated by tools/gen-rl-missions.mjs from public/games/core/missions.js. Do not edit by hand.',
    '-- Safe to run again whenever missions are added or their rewards change.',
    '',
    'insert into public.rl_missions (id, path, is_exam, minutes, xp1, xp2, xp3) values',
    lines.join(',\n'),
    'on conflict (id) do update set',
    '  path = excluded.path, is_exam = excluded.is_exam, minutes = excluded.minutes,',
    '  xp1 = excluded.xp1, xp2 = excluded.xp2, xp3 = excluded.xp3;',
    '',
  ].join('\n');
}

// { missionId: bestMedal } for every mission the player has passed with at least a bronze.
export function buildSubmission(career) {
  const out = {};
  for (const m of MISSIONS) {
    const r = career && career.missions && career.missions[m.id];
    const t = r ? Math.round(Number(r.bestTier) || 0) : 0;
    if (t >= 1 && t <= 3) out[m.id] = t;
  }
  return out;
}

// What the server will count for a submission: the same sums as rl_my_profile().
export function boardTotals(submission) {
  const rows = new Map(missionRows().map((r) => [r.id, r]));
  let xp = 0;
  let passed = 0;
  let golds = 0;
  for (const [id, tier] of Object.entries(submission || {})) {
    const r = rows.get(id);
    if (!r || !(tier >= 1 && tier <= 3)) continue;
    xp += tier === 1 ? r.xp1 : tier === 2 ? r.xp2 : r.xp3;
    if (!(r.is_exam && tier < 2)) passed += 1;
    if (tier === 3) golds += 1;
  }
  return { xp, passed, golds };
}

// A short stable fingerprint, so a sync is only sent when something changed.
export function fingerprint(submission) {
  const text = Object.keys(submission || {}).sort().map((k) => `${k}:${submission[k]}`).join('|');
  let h = 5381;
  for (let i = 0; i < text.length; i++) h = ((h << 5) + h + text.charCodeAt(i)) | 0;
  return `${Object.keys(submission || {}).length}.${(h >>> 0).toString(36)}`;
}

// ── Client-side nickname rules (the server has the final say, including the block-list) ─────────
export const NICKNAME_RE = /^[A-Za-z0-9][A-Za-z0-9_.-]{2,19}$/;
export function nicknameProblem(text) {
  const t = String(text || '');
  if (t.length < 3) return 'Use at least 3 characters.';
  if (t.length > 20) return 'Use 20 characters or fewer.';
  if (!NICKNAME_RE.test(t)) return 'Use letters, numbers, dots, dashes and underscores, starting with a letter or number.';
  return '';
}

// Where to send a player after they sign in: only a page on this site under /games/, never another address.
export function safeNext(value) {
  const v = String(value || '');
  if (!/^\/games\/[A-Za-z0-9._~\-\/?=&%]*$/.test(v)) return '';
  if (v.includes('//') || v.includes('..')) return '';
  return v.slice(0, 200);
}

